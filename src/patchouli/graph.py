"""Link/citation graph over the wiki, and the generated index."""
from __future__ import annotations

import posixpath
from collections import defaultdict
from dataclasses import dataclass, field

from . import markup
from .vault import INTEGRATED_TYPES, PAGE_TYPES, Page, Vault


@dataclass
class Graph:
    vault: Vault
    pages: dict[str, Page] = field(default_factory=dict)
    duplicates: dict[str, list[str]] = field(default_factory=dict)
    marks: dict[str, markup.PageMarkup] = field(default_factory=dict)
    _resolved: dict[str, bool] = field(default_factory=dict)

    def links(self, slug: str) -> list[markup.Link]:
        """Links that point at a wiki page (existing, or wanted) — not a same-named note or file."""
        if slug not in self.marks:
            return []
        return [l for l in self.marks[slug].links if self.resolves(l)]

    def resolves(self, l: markup.Link) -> bool:
        p = self.pages.get(l.target)
        if p is not None and l.path == p.rel:
            return True
        if l.path not in self._resolved:  # a wanted page, or a bad path to a known one — not an existing file
            self._resolved[l.path] = l.path.startswith("wiki/") and not (self.vault.root / l.path).exists()
        return self._resolved[l.path]

    def source_of(self, l: markup.Link) -> str | None:
        """The source id when a link points at that source's page."""
        return l.target if l.target in self.vault.registry and l.path == f"wiki/sources/{l.target}.md" else None

    def has_source_page(self, sid: str) -> bool:
        p = self.pages.get(sid)
        return p is not None and p.type == "source"

    def cites(self, slug: str) -> list[markup.Citation]:
        return self.marks[slug].cites if slug in self.marks else []

    def cited_sources(self, slug: str) -> list[str]:
        return list(dict.fromkeys(c.source for c in self.cites(slug)))

    def _evidence_links(self, slug: str) -> list[markup.Link]:
        m = self.marks.get(slug)
        return [l for f in m.footnotes.values() for l in f.links if self.resolves(l)] if m else []

    def sources_of(self, slug: str) -> list[str]:
        """Registered sources a page rests on: cited lines, or source pages named in its evidence
        footnotes. A "see also" link in the prose is for discovery and doesn't count."""
        out = dict.fromkeys(self.cited_sources(slug))
        for l in self._evidence_links(slug):
            if self.source_of(l) and l.target != slug:
                out.setdefault(l.target)
        return list(out)

    def dependencies(self, slug: str) -> dict[str, str]:
        """What a page builds on, target -> how: typed relations (other than loose ones like
        `related`), pages named in its evidence footnotes ('evidence'), cited sources ('cite').
        Plain links in the prose are navigation, not dependencies."""
        deps = {t: rel for t, rel in self.relations(slug).items() if rel not in markup.LOOSE}
        for l in self._evidence_links(slug):
            deps.setdefault(l.target, "evidence")
        for sid in self.cited_sources(slug):
            deps.setdefault(sid, "cite")
        deps.pop(slug, None)
        return deps

    def relations(self, slug: str) -> dict[str, str]:
        """target -> the strongest relation used from this page: a contradiction beats other
        labels, any label beats a loose one (`related`) or a plain link."""
        def rank(rel):
            return 2 if rel in markup.CONTRADICTS else 0 if rel in markup.LOOSE else 1
        out: dict[str, str] = {}
        for l in self.links(slug):
            if l.target not in out or rank(l.rel) > rank(out[l.target]):
                out[l.target] = l.rel
        return out


def build(vault: Vault) -> Graph:
    g = Graph(vault)
    for page in vault.iter_pages():
        if page.slug in g.pages:
            g.duplicates.setdefault(page.slug, [g.pages[page.slug].rel]).append(page.rel)
            continue
        g.pages[page.slug] = page
        g.marks[page.slug] = markup.parse(page.body, page.body_start, page.dir)
    return g


# ------------------------------------------------------------------ index
_SECTIONS = [("hub", "Hubs"), ("concept", "Concepts"), ("synthesis", "Syntheses"), ("answer", "Answers"),
             ("source", "Sources")]


def _link(p: Page, base: str = "wiki") -> str:
    return f"[{p.title}]({posixpath.relpath(p.rel, base)})"


def render_index(g: Graph, state: dict | None = None) -> str:
    reg = g.vault.registry
    state = state or {}
    out = ["# Index", "",
           "<!-- Generated by `patchouli sync`. Do not edit by hand: change page titles/summaries instead. -->", ""]
    by_type: dict[str, list[Page]] = defaultdict(list)
    for p in g.pages.values():
        by_type[p.type if p.type in PAGE_TYPES else "other"].append(p)
    for ptype, heading in _SECTIONS + [("other", "Untyped pages")]:
        pages = sorted(by_type.get(ptype, []), key=lambda p: (p.slug != "overview", p.title.lower()))
        if not pages:
            continue
        out += [f"## {heading} ({len(pages)})", ""]
        for p in pages:
            extra = []
            if ptype == "source":
                authors = p.meta.get("authors")
                if isinstance(authors, list):
                    authors = ", ".join(authors[:2]) + (" et al." if len(authors) > 2 else "")
                bits = [b for b in (authors, str(p.meta.get("year") or "")) if b]
                if bits:
                    extra.append(" ".join(bits))
            elif ptype in INTEGRATED_TYPES:
                n = len(g.sources_of(p.slug))
                extra.append(f"{n} source{'s' if n != 1 else ''}")
                if ptype == "answer" and p.meta.get("status"):
                    extra.append(str(p.meta["status"]))
            changed = state.get(p.slug, {}).get("changed", "")[:10]
            if changed and ptype != "hub":
                extra.append(f"updated {changed}")
            line = f"- {_link(p)}"
            if p.summary:
                line += f" — {p.summary}"
            if extra:
                line += f" · _{' · '.join(extra)}_"
            out.append(line)
        out.append("")
    tensions = sorted({(s, l.target, l.rel) for s in g.marks for l in g.links(s)
                       if l.rel in markup.CONTRADICTS and l.target in g.pages and l.target != s})
    if tensions:
        out += [f"## Tensions ({len(tensions)})", ""]
        out += [f"- {_link(g.pages[s])} {rel.replace('-', ' ')} {_link(g.pages[t])}" for s, t, rel in tensions]
        out.append("")
    wanted: dict[str, set] = defaultdict(set)
    for s in g.marks:
        for l in g.links(s):
            if l.target not in g.pages:
                wanted[l.target].add(s)
    if wanted:
        out += [f"## Wanted pages ({len(wanted)})", "", "Linked to, but not written yet.", ""]
        for t, refs in sorted(wanted.items(), key=lambda kv: (-len(kv[1]), kv[0])):
            names = ", ".join(_link(g.pages[r]) for r in sorted(refs)[:5])
            out.append(f"- `{t}` — from {names}" + (" …" if len(refs) > 5 else ""))
        out.append("")
    pending = [(sid, e) for sid, e in sorted(reg.items()) if not g.has_source_page(sid)]
    if pending:
        out += [f"## Awaiting ingestion ({len(pending)})", ""]
        for sid, e in pending:
            st = f"{e.get('lines', 0)} lines of reading text" if e.get("text") else "not extracted"
            out.append(f"- `{sid}` — {e.get('title') or sid} · _{st}_")
        out.append("")
    return "\n".join(out).rstrip() + "\n"


def write_index(vault: Vault, g: Graph, state: dict) -> None:
    text = render_index(g, state)
    if not vault.index_path.exists() or vault.index_path.read_text(encoding="utf-8") != text:
        vault.index_path.write_text(text, encoding="utf-8")
